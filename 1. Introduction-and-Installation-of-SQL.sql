-------------------------------------------------
-- WHAT IS SQL?
-------------------------------------------------

-- SQL stands for Structured Query Language.

-- SQL is used to interact with databases.

-- SQL helps users:
-- Retrieve data
-- Insert data
-- Update data
-- Delete data
-- Manage database objects


-------------------------------------------------
-- WHY DO WE USE SQL?
-------------------------------------------------

-- 1. Simplifies working with large datasets.
-- 2. Enables efficient data management.
-- 3. Works with most database systems.
-- 4. Supports data analysis and reporting.
-- 5. Industry standard database language.


-------------------------------------------------
-- SQL IS USED IN THE FOLLOWING JOB ROLES
-------------------------------------------------

-- Data Analyst
-- Data Engineer
-- Data Scientist
-- SQL Developer
-- Business Analyst
-- Quality Analyst


-------------------------------------------------
-- WHAT IS DATA?
-------------------------------------------------

-- Anything and everything can be considered data.

-- Data can be:
-- Text
-- Numbers
-- Images
-- Videos
-- Documents
-- Single Characters

-- Example:
-- Employee Records
-- Customer Information
-- Bank Transactions
-- Product Details


-------------------------------------------------
-- WHAT IS A DATABASE?
-------------------------------------------------

-- A Database is a collection of data
-- stored digitally for easy access.

-- Database allows:
-- Storing Data
-- Managing Data
-- Organizing Data
-- Retrieving Data


-------------------------------------------------
-- WHAT IS DBMS?
-------------------------------------------------

-- DBMS stands for
-- Database Management System.

-- Examples:
-- PostgreSQL
-- MySQL
-- Oracle
-- SQL Server


-------------------------------------------------
-- PURPOSE OF STORING DATA IN DATABASE
-------------------------------------------------

-- Data can be:
-- Easily Accessed
-- Easily Modified
-- Protected
-- Analyzed


-------------------------------------------------
-- TABLE STRUCTURE
-------------------------------------------------

-- Data inside databases is generally
-- stored in tables.

-- Table consists of:
-- Rows (Records)
-- Columns (Fields)


-------------------------------------------------
-- RDBMS
-------------------------------------------------

-- RDBMS stands for
-- Relational Database Management System.

-- Data is stored in tables.

-- Tables are connected using relationships.

-- Popular RDBMS:
-- PostgreSQL
-- MySQL
-- Oracle
-- SQL Server


